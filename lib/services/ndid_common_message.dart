          'ตัวตนที่ท่านเลือก กรุณาเลือกผู้ให้บริการยืนยันตัวตนรายอื่นที่ท่าน'
          'เคยลงทะเบียนและมีโมบายแอปพลิเคชัน',
      30400 => 'ขออภัย ข้อมูลของท่านไม่เป็นปัจจุบัน กรุณาติดต่อผู้ให้บริการ'
