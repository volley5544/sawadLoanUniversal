import 'dart:math';

/// The NDID **Common Message** standard, as an RP must show it.
///
/// Source: *005 แนวทางการพัฒนาบริการ NDID สำหรับสมาชิก* Rev. 1.0 (11 Feb 2021),
/// §6.2.1 "มาตรฐาน Common Message สำหรับบทบาทผู้ให้บริการ (Relying Party: RP)",
/// pages 31–39. Added 2026-08-28 after NDID rejected the app review — issue 3
/// asked for exactly these strings.
///
/// The wording here is **quoted from that document**, and was checked against
/// the PDF's own extracted text on **2026-09-01**: all 18 IdP/AS messages,
/// [chooseIdp], [waitingForIdp] and [generalFailure] matched verbatim, with
/// exactly the two deviations declared below ([cancelledOrChangedIdp] and
/// [requestMessage]).
///
/// ⚠ **No test enforces that** — `test/ndid_common_message_test.dart` checks
/// structure (every documented code has its own message, no `[IdP]`/`XXX`
/// placeholder leaks, an unknown code degrades to the catch-all), not the text.
/// It cannot: the guideline lives in git-ignored `dap/`, so a test reading it
/// would fail in CI on a missing file. Re-run the comparison by hand after
/// touching any string here — normalise whitespace and map `ำ` to `า`, since the
/// PDF stores that vowel decomposed.
///
/// Three rules from the same section shape the API:
///
/// * §6.2.1 bullet 4 — where the document writes `[RP]` or `[IdP]`, the member
///   must substitute the **marketing name**, not the literal word. Hence
///   [rpMarketingName] and the `idpName` arguments.
/// * §6.2.1 bullet 2 — a member may adjust wording for clarity, provided the
///   customer knows what happened and what to do next. That is the licence
///   under which [requestMessage] drops the document's AS clause; see there.
/// * Page 38 note — the Transaction Ref is generated by the RP, is **digits
///   only**, and is 5–9 digits long. See [NdidTransactionRef].
abstract final class NdidCommonMessage {
  /// The RP Marketing Name shown to customers, per §6.2.1 bullet 4.
  static const String rpMarketingName = 'บริษัท ศรีสวัสดิ์ พาวเวอร์ 2014 จำกัด';

  /// Contact shown by the AS-error messages, which the standard writes as
  /// "RP Contact XXX".
  ///
  /// **Deliberately empty by default.** Four AS messages tell the customer to
  /// contact us, and a wrong phone number in front of a customer is worse than
  /// none — so rather than invent one, an unset value falls back to
  /// "ติดต่อผู้ให้บริการ". Set it with
  /// `--dart-define=NDID_RP_CONTACT=ศูนย์บริการลูกค้า 1652` once the real
  /// number is confirmed.
  static const String rpContact =
      String.fromEnvironment('NDID_RP_CONTACT', defaultValue: '');

  /// `ติดต่อ <contact>` — or the generic form when no contact is configured.
  static String get _contactClause =>
      rpContact.isEmpty ? 'ติดต่อผู้ให้บริการ' : 'ติดต่อ $rpContact';

  /// §6.2.1 [2] — shown before the customer picks an IdP.
  static const String chooseIdp =
      'กรุณาเลือกผู้ให้บริการยืนยันตัวตน ที่ท่านเคยลงทะเบียนไว้เพื่อยืนยันตัวตน'
      'และมีโมบายแอปพลิเคชันของผู้ให้บริการยืนยันตัวตนดังกล่าว';

  /// §6.2.1 [3] — shown after the customer picks an IdP, while the request is
  /// waiting. The 60 minutes is the standard RP request timeout, which is what
  /// `NdidApi.createVerifyRequest` asks for.
  static const String waitingForIdp =
      'กรุณาไปยืนยันตัวตนที่โมบายแอปพลิเคชันของผู้ให้บริการที่ท่านเลือก '
      'ภายใน 60 นาที และกลับมาทำรายการต่อที่นี่';

  /// §6.2.1 [5] — the customer cancelled the request or switched IdP.
  ///
  /// ⚠ One word differs from the document, which ends "กรุณาเลือก **IdP**
  /// รายอื่น". Bullet 4 of the same section says not to show the customer the
  /// literal word "IdP", and every other message in the table spells it
  /// "ผู้ให้บริการยืนยันตัวตนรายอื่น" — so the standard contradicts itself here
  /// and this follows the rule rather than the typo.
  static const String cancelledOrChangedIdp =
      'ท่านได้ยกเลิกรายการคำขอหรือเปลี่ยนผู้ให้บริการยืนยันตัวตน '
      'กรุณาเลือกผู้ให้บริการยืนยันตัวตนรายอื่น';

  /// Page 39 — the catch-all the standard gives for RP API V4, used for any
  /// failure with no more specific message (an unknown error code included).
  static const String generalFailure =
      'ท่านไม่สามารถทำรายการได้ในขณะนี้ '
      'กรุณาทำรายการใหม่หรือเลือกผู้ให้บริการยืนยันตัวตนรายอื่น';

  /// The Request Message sent to the IdP and shown in the IdP's own app
  /// (§6.2.1 [28], page 37).
  ///
  /// The document's template is:
  ///
  /// > "ท่านกำลังยืนยันตัวตนเพื่อใช้ตามวัตถุประสงค์ของ \[RP\] และประสงค์ให้ส่ง
  /// > ข้อมูลจาก \[AS 1, AS 2, …\] (Transaction Ref:12345678)"
  ///
  /// **The AS clause is rendered only when data really is requested**
  /// ([asNames] non-empty), which since 2026-09-10 is the normal case:
  /// `createVerifyRequest` calls `/rp/verify-with-data` and names the one bank
  /// it asks for `001.cust_info_001` from — the same bank the customer picked
  /// as their IdP.
  ///
  /// It stays conditional because the fallback path is still real: when no AS
  /// can be matched to the chosen IdP the request degrades to plain
  /// `/rp/verify` with no `data_request_list`, and naming a bank there would
  /// tell the customer their data is being fetched when it is not. §6.2.1
  /// bullet 2 permits adjusting the wording so long as the customer understands
  /// what is happening; describing exactly the parties actually in the request
  /// is the honest reading in both directions.
  ///
  /// ⚠ NDID's reviewer's reference image shows this clause populated, so the
  /// **with-data** path is the one the submitted user journey describes — see
  /// Outstanding #25.
  ///
  /// ⚠ **[transactionRef] is normally omitted now** (2026-08-31). The srisawad
  /// NDID gateway generates the Transaction Ref itself and appends the
  /// `(Transaction Ref: …)` clause to this message server-side, then returns the
  /// value on `POST /rp/verify` and every `GET /rp/verify/{ref}` so the waiting
  /// screen can quote it. Passing one here would put a *second*, different
  /// reference in front of the customer — which is the state NDID rejected the
  /// review over, wearing the opposite mistake. Pass one only for a gateway that
  /// does not compose the clause itself (the DAP/SIT node).
  static String requestMessage({
    String? transactionRef,
    List<String> asNames = const [],
  }) {
    const base =
        'ท่านกำลังยืนยันตัวตนเพื่อใช้ตามวัตถุประสงค์ของ$rpMarketingName';
    // Marketing names only, never a node id (§6.2.1 bullet 4). Blanks are
    // dropped rather than rendered as an empty slot in the list.
    final sources = asNames
        .map((name) => name.trim())
        .where((name) => name.isNotEmpty)
        .toList(growable: false);
    final buffer = StringBuffer(base);
    if (sources.isNotEmpty) {
      buffer.write(' และประสงค์ให้ส่งข้อมูลจาก ${sources.join(', ')}');
    }
    if (transactionRef != null && transactionRef.isNotEmpty) {
      // No space after the colon: that is how p.38's template writes it, and
      // how the srisawad gateway actually renders the clause it appends —
      // verified 2026-09-10 against a KBank consent screen showing
      // `(Transaction Ref:312461174)`. This branch only runs for a gateway
      // that composes no clause of its own, so matching the observed format is
      // what keeps the two paths indistinguishable to a customer.
      buffer.write(' (Transaction Ref:$transactionRef)');
    }
    return buffer.toString();
  }

